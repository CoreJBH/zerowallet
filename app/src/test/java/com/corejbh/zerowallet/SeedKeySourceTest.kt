package com.corejbh.zerowallet

import java.io.File
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * The wallet's key is made inside the Android Keystore, not generated in software and imported.
 *
 * The ninth review found `SecureStore` generating an AES key with the default provider and
 * handing the material to `KeyStore.setEntry` twice, so the key existed as a byte array in
 * this process for as long as the import took. Every safekeeping property this app claims
 * rests on the key never leaving the Keystore, and a review can only see that in the shape of
 * the code that creates it. Hence a source check: an instrumentation test cannot observe a
 * key that is not supposed to be observable, and there is no Keystore on the unit-test JVM.
 *
 * `SecretStore` already does it the right way and is the reference these rules are drawn from.
 */
class SeedKeySourceTest {

    private val secureStore = "src/main/java/com/corejbh/zerowallet/core/SecureStore.kt"

    private fun source(relative: String): String {
        var dir: File? = File("").absoluteFile
        repeat(5) {
            listOf(File(dir, relative), File(dir, "app/$relative")).firstOrNull { it.isFile }
                ?.let { return it.readText() }
            dir = dir?.parentFile
        }
        throw AssertionError("Could not find $relative from ${File("").absolutePath}")
    }

    @Test
    fun theKeyIsGeneratedInTheAndroidKeystore() {
        val text = source(secureStore)
        assertTrue(
            "The wallet key must be generated by the Keystore provider",
            text.contains("KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, KEYSTORE)") ||
                text.contains("KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, \"AndroidKeyStore\")")
        )
        assertTrue(
            "and the Keystore name has to be the Android one",
            text.contains("private const val KEYSTORE = \"AndroidKeyStore\"")
        )
    }

    @Test
    fun noSoftwareKeyIsImportedIntoTheKeystore() {
        val text = source(secureStore)
        // The two calls the review objected to: importing generated material, and the
        // KeyProtection builder that went with it.
        assertFalse(
            "SecureStore imports software-generated key material again",
            text.contains("setEntry(")
        )
        assertFalse("KeyProtection is only needed for imported keys", text.contains("KeyProtection"))
        assertFalse(
            "A key generated outside the Keystore provider has no business in SecureStore",
            text.contains("KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES)\n")
        )
        assertFalse(
            "and neither has a SecretKeySpec built from bytes",
            text.contains("SecretKeySpec(")
        )
    }

    @Test
    fun aSealThatNeedsAuthenticationSaysSoInsteadOfUsingAWeakerKey() {
        val text = source(secureStore)
        assertTrue(
            "The seal reports that an authentication is needed",
            text.contains("object NeedsAuthentication : SeedSeal()")
        )
        assertTrue(
            "and the wallet refuses to write anything in that case",
            text.contains("SealAttempt.NeedsAuthentication -> return SeedSeal.NeedsAuthentication")
        )
    }

    @Test
    fun theNodeNeverSealsThePhraseItself() {
        // One way in: every wallet path goes through SecureStore, so there is one place where
        // the key, the binding and the fallback are decided.
        // The wallet layer since the 1.2.0 split, plus every other core file: the Keystore
        // key is generated in SecureStore and nowhere else, and a seal goes through it.
        val walletLayer = source("src/main/java/com/corejbh/zerowallet/core/WalletLayer.kt")
        assertFalse(walletLayer.contains("KeyGenerator"))
        assertTrue(walletLayer.contains("core.secureStore.saveSeed("))
        assertTrue(walletLayer.contains("core.secureStore.canSeal()"))
        val coreDir = java.io.File(walletLayer.substringBefore("WalletLayer.kt"))
        coreDir.listFiles { file -> file.extension == "kt" }
            ?.filter { it.name != "SecureStore.kt" }
            ?.forEach { file ->
                assertFalse(
                    "${file.name} seals a record outside SecureStore",
                    file.readText().contains("KeyGenerator")
                )
            }
    }
}
